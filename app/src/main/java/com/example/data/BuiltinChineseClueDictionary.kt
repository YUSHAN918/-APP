    fun getClueInfo(text: String): ClueInfo? {
        val trimmed = text.trim()
        dictionary[trimmed]?.let { return it }
        // 如果是多字词，且没有直接映射，尝试提取其中的字组词
        if (trimmed.length == 1) {
            return ClueInfo(clueText = "${trimmed}字", meaningHint = "汉字：$trimmed")
        }
        return null
    }
