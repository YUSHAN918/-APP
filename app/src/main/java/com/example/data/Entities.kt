    val ttsPrompt: String = "",
    val targetAnswer: String = "",
    val clueText: String = "",
    val meaningHint: String = "",
    val errorReason: String = ""
) {
    fun getEffectiveVisiblePrompt(): String {
        return if (visiblePrompt.isNotBlank()) visiblePrompt else correctText
    }

    fun getEffectiveTtsPrompt(): String {
        return if (ttsPrompt.isNotBlank()) ttsPrompt else correctText
    }

    fun getEffectiveTargetAnswer(): String {
        return if (targetAnswer.isNotBlank()) targetAnswer else correctText
    }
}

