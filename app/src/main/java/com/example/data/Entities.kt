@Entity(tableName = "words")
data class WordItem(
    @PrimaryKey(autoGenerate = true) val id: Int = 0,
    val text: String,
    val type: String, // 字, 词语, 成语, 句子, 古诗句, 课文重点句
    val unitName: String,
    val difficulty: String, // 普通, 易错, BOSS
    val promptMode: String = "FULL_WORD", // FULL_WORD, CLOZE_CHAR, CONTEXT_CLUE
    val hiddenIndicesStr: String = "", // e.g. "0" or "0,1"
    val visiblePrompt: String = "", // e.g. "__桃"
    val ttsPrompt: String = "", // e.g. "请写‘樱桃’的第一个字"
    val contextText: String = "", // e.g. "破晓的晓"
    val targetAnswer: String = "", // e.g. "樱"
    val clueText: String = "", // e.g. 白昼, 破晓
    val meaningHint: String = "", // e.g. 白天, 天刚亮的时候
    val exampleText: String = "",
    val sourceLesson: String = "",
    val promptAutoGenerated: Boolean = true,
    val promptManuallyEdited: Boolean = false,
    val promptQuality: String = "GOOD", // GOOD, NEED_CONTEXT, MANUAL, FALLBACK
    val visibilityPolicy: String = "TEST_SAFE" // TEST_SAFE, PRACTICE_HINT, REVIEW_ONLY
) {
    fun getEffectiveTargetAnswer(): String = if (targetAnswer.isNotBlank()) targetAnswer else text

    fun getEffectiveVisiblePrompt(isPracticeMode: Boolean = false): String {
        if (visibilityPolicy == "PRACTICE_HINT" || isPracticeMode) {
            return if (visiblePrompt.isNotBlank()) visiblePrompt else if (clueText.isNotBlank()) clueText else text
        }

        // TEST_SAFE 测验安全模式
        val target = getEffectiveTargetAnswer()
        val isSingleCharTarget = target.length == 1

        // 1. 如果 WordItem.visiblePrompt 非空：显示 maskTargetAnswerInPrompt(visiblePrompt, target)
        if (visiblePrompt.isNotBlank()) {
            return com.example.util.PromptSecurityUtil.maskTargetAnswerInPrompt(visiblePrompt, target)
        }

        // 2. 如果 visiblePrompt 为空，但 clueText 非空且 targetAnswer 是单字（或语境/填空模式）
        if (clueText.isNotBlank() && (isSingleCharTarget || promptMode == "CONTEXT_CLUE" || promptMode == "CLOZE_CHAR")) {
            return com.example.util.PromptSecurityUtil.buildSafeCluePrompt(clueText, target)
        }

        // 3. 如果 promptMode == CONTEXT_CLUE：不允许降级成“请根据语音写出词语”，除非 clueText 和 visiblePrompt 都为空
        if (promptMode == "CONTEXT_CLUE" && clueText.isNotBlank()) {
            return com.example.util.PromptSecurityUtil.buildSafeCluePrompt(clueText, target)
        }

        // 4. 只有在 FULL_WORD 且没有任何 visiblePrompt / clueText 时，才显示：请根据语音写出词语
        return "请根据语音写出词语"
    }

    fun getEffectiveSubPrompt(isPracticeMode: Boolean = false): String {
        if (visibilityPolicy == "PRACTICE_HINT" || isPracticeMode) {
            if (ttsPrompt.isNotBlank()) return ttsPrompt
            if (clueText.isNotBlank()) return "请写“${clueText}”的“${getEffectiveTargetAnswer()}”"
            return text
        }

        return if (promptMode == "FULL_WORD") {
            "请根据语音写出词语"
        } else {
            "请根据语音写出空缺的字"
        }
    }

    fun getFormattedAudioPrompt(): String {
        if (ttsPrompt.isNotBlank()) return ttsPrompt
        if (text.length == 1 && clueText.isNotBlank()) {
            return "请写“${clueText}”的“${text}”"
        }
        if (meaningHint.isNotBlank()) {
            return "请根据提示写出词语：${meaningHint}。${text}"
        }
        return "请写词语：$text"
    }

    fun getEffectiveTtsPrompt(): String = getFormattedAudioPrompt()
}

